<#
.SYNOPSIS
    Generates the third-party license inventory for a squeezegram build.

.DESCRIPTION
    Lists every Rust crate in the Windows dependency graph (cargo metadata, target
    x86_64-pc-windows-msvc) and every npm production package (pnpm licenses list --prod),
    with version, declared license and repository. Packages under a copyleft license
    (MPL, LGPL, GPL, AGPL, EPL, CDDL) are listed again in their own section.
    With -IncludeTexts, the LICENSE/COPYING/NOTICE files found in each package folder are
    appended, which is what a release needs to ship next to the binary.

    The Rust list comes from the resolved graph, so it can include build-time crates
    (tauri-build, proc macros) that do not end up in the binary. Over-listing is harmless
    for a notice file.

    Native components that are not Rust crates or npm packages (TDLib, OpenSSL, zlib inside
    tdjson.dll, ffmpeg) are not detected here: they are described by hand in
    THIRD-PARTY-NOTICES.md at the repository root.

.PARAMETER OutFile
    Output path. Default: src-tauri\target\notices\THIRD-PARTY-DEPENDENCIES.md (ignored by Git).

.PARAMETER IncludeTexts
    Append the license files of each package.

.EXAMPLE
    pwsh -File scripts\generate-notices.ps1
.EXAMPLE
    pwsh -File scripts\generate-notices.ps1 -IncludeTexts -OutFile dist\THIRD-PARTY-LICENSES.md
#>
[CmdletBinding()]
param(
    [string] $OutFile,
    [switch] $IncludeTexts
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$tauriDir = Join-Path $root 'src-tauri'
if (-not $OutFile) {
    $OutFile = Join-Path $tauriDir 'target\notices\THIRD-PARTY-DEPENDENCIES.md'
}
$copyleft = 'MPL|LGPL|GPL|AGPL|EPL|CDDL'
$licenseFilePattern = '^(LICEN[CS]E|COPYING|NOTICE|COPYRIGHT)'

function Get-LicenseFiles([string] $Dir) {
    if (-not $Dir -or -not (Test-Path -LiteralPath $Dir)) { return @() }
    Get-ChildItem -LiteralPath $Dir -File | Where-Object { $_.Name -match $licenseFilePattern } | Sort-Object Name
}

# Rust crates
Push-Location $tauriDir
try {
    $metaJson = cargo metadata --format-version 1 --locked --filter-platform x86_64-pc-windows-msvc
    if ($LASTEXITCODE -ne 0) { throw 'cargo metadata failed' }
} finally {
    Pop-Location
}
$meta = $metaJson | ConvertFrom-Json
$inGraph = @{}
foreach ($node in $meta.resolve.nodes) { $inGraph[$node.id] = $true }
$crates = $meta.packages |
    Where-Object { $inGraph.ContainsKey($_.id) -and $_.source } |
    Sort-Object name, version |
    ForEach-Object {
        [pscustomobject]@{
            Kind       = 'crate'
            Name       = $_.name
            Version    = $_.version
            License    = if ($_.license) { $_.license } elseif ($_.license_file) { "see $($_.license_file)" } else { 'UNKNOWN' }
            Repository = $_.repository
            Dir        = Split-Path -Parent $_.manifest_path
        }
    }

# npm production packages
Push-Location $root
try {
    $npmJson = pnpm licenses list --prod --json
    if ($LASTEXITCODE -ne 0) { throw 'pnpm licenses list failed (run pnpm install first)' }
} finally {
    Pop-Location
}
$npmByLicense = $npmJson | ConvertFrom-Json
$npm = foreach ($prop in $npmByLicense.PSObject.Properties) {
    foreach ($pkg in $prop.Value) {
        for ($i = 0; $i -lt $pkg.versions.Count; $i++) {
            [pscustomobject]@{
                Kind       = 'npm'
                Name       = $pkg.name
                Version    = $pkg.versions[$i]
                License    = $prop.Name
                Repository = $pkg.homepage
                Dir        = if ($pkg.paths -and $pkg.paths.Count -gt $i) { $pkg.paths[$i] } else { $null }
            }
        }
    }
}
$npm = $npm | Sort-Object Name, Version

$all = @($crates) + @($npm)
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('# squeezegram third-party dependencies')
[void]$sb.AppendLine()
[void]$sb.AppendLine("Generated by scripts/generate-notices.ps1 on $((Get-Date).ToUniversalTime().ToString('yyyy-MM-dd')) (UTC).")
[void]$sb.AppendLine("Rust crates: $(@($crates).Count). npm production packages: $(@($npm).Count).")
[void]$sb.AppendLine('Native components (TDLib, OpenSSL, zlib, ffmpeg) are covered in THIRD-PARTY-NOTICES.md.')
[void]$sb.AppendLine()

$weak = $all | Where-Object { $_.License -match $copyleft }
[void]$sb.AppendLine('## Copyleft licenses')
[void]$sb.AppendLine()
if ($weak) {
    [void]$sb.AppendLine('Used unmodified. The source code of each package is available at the repository listed.')
    [void]$sb.AppendLine()
    foreach ($p in $weak) {
        [void]$sb.AppendLine("- $($p.Kind) ``$($p.Name)`` $($p.Version), $($p.License), $($p.Repository)")
    }
} else {
    [void]$sb.AppendLine('None.')
}
[void]$sb.AppendLine()

foreach ($section in @(@('Rust crates', $crates), @('npm packages', $npm))) {
    [void]$sb.AppendLine("## $($section[0])")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('| Name | Version | License | Source |')
    [void]$sb.AppendLine('|---|---|---|---|')
    foreach ($p in $section[1]) {
        [void]$sb.AppendLine("| $($p.Name) | $($p.Version) | $($p.License -replace '\|', '\|') | $($p.Repository) |")
    }
    [void]$sb.AppendLine()
}

if ($IncludeTexts) {
    [void]$sb.AppendLine('## License texts')
    [void]$sb.AppendLine()
    $missing = 0
    foreach ($p in $all) {
        $files = @(Get-LicenseFiles $p.Dir)
        if (-not $files) { $missing++; continue }
        [void]$sb.AppendLine("### $($p.Name) $($p.Version)")
        [void]$sb.AppendLine()
        foreach ($f in $files) {
            [void]$sb.AppendLine("#### $($f.Name)")
            [void]$sb.AppendLine()
            [void]$sb.AppendLine('```text')
            [void]$sb.AppendLine(([IO.File]::ReadAllText($f.FullName)).TrimEnd())
            [void]$sb.AppendLine('```')
            [void]$sb.AppendLine()
        }
    }
    if ($missing) {
        Write-Warning "$missing package(s) ship no LICENSE/COPYING/NOTICE file in their folder; check them by hand."
    }
}

$outDir = Split-Path -Parent $OutFile
if ($outDir) { New-Item -ItemType Directory -Force -Path $outDir | Out-Null }
[IO.File]::WriteAllText($OutFile, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $OutFile ($(@($crates).Count) crates, $(@($npm).Count) npm packages, $(@($weak).Count) copyleft)"
