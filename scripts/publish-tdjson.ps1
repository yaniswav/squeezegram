   (https://www.sqlite.org/copyright.html); the SQLCipher changes are under the Zetetic
   BSD-style license (https://www.zetetic.net/sqlcipher/license/).

squeezegram's own licence and the notices of its other dependencies are in the repository:
https://github.com/$Repository/blob/main/THIRD-PARTY-NOTICES.md
"@
$work = Join-Path ([IO.Path]::GetTempPath()) ("publish-tdjson-" + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $work | Out-Null
try {
    $noticesPath = Join-Path $work 'tdjson-NOTICES.txt'
    [IO.File]::WriteAllText($noticesPath, ($notices -replace "`r?`n", "`r`n"), (New-Object System.Text.UTF8Encoding($false)))

    # Release body.
    $body = @"
tdjson.dll built from TDLib 1.8.68 (https://github.com/tdlib/td, commit $SourceCommit) for squeezegram, Windows x86_64.

SHA-256: $($DllSha256.ToLowerInvariant())

This is an input of squeezegram's release build, not an app release. The licences (Boost Software License 1.0 for TDLib, Apache-2.0 for the statically linked OpenSSL, zlib licence for zlib) are in tdjson-NOTICES.txt.
"@
    $bodyPath = Join-Path $work 'body.md'
    [IO.File]::WriteAllText($bodyPath, $body, (New-Object System.Text.UTF8Encoding($false)))

    # Does the release exist already, and what does it hold?
    $json = & gh release view $Tag --repo $Repository --json assets,isDraft,isPrerelease 2>&1
    $exists = ($LASTEXITCODE -eq 0)
    if (-not $exists -and ($json -join "`n") -notmatch 'release not found') { throw "gh release view failed: $($json -join ' ')" }

    $toUpload = @()
    if ($exists) {
        $release = ($json -join "`n") | ConvertFrom-Json
        $names = @($release.assets | ForEach-Object { $_.name })
        $digestOf = @{}
        foreach ($asset in $release.assets) {
            $digest = if ($asset.PSObject.Properties.Name -contains 'digest') { $asset.digest } else { $null }
            $digestOf[$asset.name] = $digest
        }
        $expected = @{
            'tdjson.dll'         = $DllPath
            'tdjson-NOTICES.txt' = $noticesPath
        }
        foreach ($name in $expected.Keys) {
            $localHash = (Get-FileHash -LiteralPath $expected[$name] -Algorithm SHA256).Hash.ToLowerInvariant()
            if ($names -notcontains $name) { $toUpload += $expected[$name]; continue }
            if ($digestOf[$name] -ne "sha256:$localHash") { $toUpload += $expected[$name] }
        }
        if ($release.isDraft) { Write-Warning "The release $Tag is a draft: publish it from the GitHub page, this script does not." }
        if ($toUpload.Count -eq 0) {
            Write-Host "The release $Tag already holds tdjson.dll and tdjson-NOTICES.txt with the same content. Nothing to do."
            return
        }
    }

    Write-Host ''
    if ($exists) {
        Write-Host "The release $Tag exists in $Repository. Will upload (replacing same-named assets):"
        $toUpload | ForEach-Object { Write-Host "  $(Split-Path -Leaf $_)" }
    }
    else {
        Write-Host "Will CREATE in ${Repository}: release '$Title' (tag $Tag, pre-release, not latest) with:"
        Write-Host "  tdjson.dll           $DllPath"
        Write-Host "  tdjson-NOTICES.txt   (generated)"
        Write-Host "The tag is created on the head of the default branch."
    }
    $answer = Read-Host 'Type "publish" to continue, anything else to stop'
    if ($answer -ne 'publish') { Write-Host 'Stopped. Nothing was uploaded.'; return }

    if ($exists) {
        & gh release upload $Tag --repo $Repository --clobber @toUpload
        if ($LASTEXITCODE -ne 0) { throw "gh release upload failed with exit code $LASTEXITCODE" }
    }
    else {
        & gh release create $Tag --repo $Repository --title $Title --notes-file $bodyPath --prerelease --latest=false $DllPath $noticesPath
        if ($LASTEXITCODE -ne 0) { throw "gh release create failed with exit code $LASTEXITCODE" }
    }
    Write-Host "Done: https://github.com/$Repository/releases/tag/$Tag"
    Write-Host "Asset URL used by release.yml: https://github.com/$Repository/releases/download/$Tag/tdjson.dll"
}
finally {
    Remove-Item -LiteralPath $work -Recurse -Force -ErrorAction SilentlyContinue
}
