<#
.SYNOPSIS
    Publishes the pinned tdjson.dll as an asset of the release "tdjson-1.8.68" of this repository.

.DESCRIPTION
    .github\workflows\release.yml downloads tdjson.dll from that release and checks its SHA-256
    against the pin before building. Run this script ONCE, by hand, with the gh CLI logged in
    (gh auth login) as an account that can write to the repository. CI never runs it.

    What it does:
      1. checks that the file at -DllPath has the pinned SHA-256 (it stops otherwise);
      2. writes tdjson-NOTICES.txt (licences of TDLib and of the libraries linked into it, source
         commit, SHA-256) to a temporary folder;
      3. shows what it is about to do and asks for an interactive confirmation (type "publish");
      4. creates the release tdjson-1.8.68 (published, marked pre-release, not "latest") with
         tdjson.dll and tdjson-NOTICES.txt.

    Idempotent: if the release already exists, nothing is recreated. Assets that are already
    there with the same content are left alone; missing or different ones are uploaded (a
    different one replaces the old one, after the same confirmation).

    The release is a pre-release on purpose: it is not "the latest release" of the project, so
    it never becomes the project's latest release (the updater reads channel-v<N>, not this tag). The tag is created
    on the current head of the default branch; the DLL does not come from that commit (it is built
    from TDLib's sources, see the notices), the tag is only a name for the release.

    This is the one place in the repository where the DLL is uploaded. The file itself is never
    committed (tdjson*.dll is git-ignored).

.EXAMPLE
    pwsh -File scripts\publish-tdjson.ps1 -DllPath $env:LOCALAPPDATA\squeezegram\tdlib\bin\tdjson.dll
#>
[CmdletBinding()]
param(
    # The tdjson.dll to publish (the pinned build).
    [Parameter(Mandatory = $true)]
    [string] $DllPath,
    [string] $Repository = 'yaniswav/squeezegram'
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# Same pin as scripts\stage-tdjson.ps1 and src-tauri\src\transport\tdlib\library.rs.
$DllSha256 = '048AF1D1C97EF9B860DD5DE132C4D2D901D444691EC86FC15012E5896DBDE6B8'
$Tag = 'tdjson-1.8.68'
$Title = 'TDLib 1.8.68 build for squeezegram'
$SourceCommit = 'c15d3f5a5de6e3ba5839822c451152e5e18bb700'

if ($Repository -notmatch '^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$') { throw "Repository '$Repository' is not owner/name" }
if (-not (Test-Path -LiteralPath $DllPath -PathType Leaf)) { throw "Not found: $DllPath" }
$DllPath = (Resolve-Path -LiteralPath $DllPath).ProviderPath
$actual = (Get-FileHash -LiteralPath $DllPath -Algorithm SHA256).Hash.ToUpperInvariant()
if ($actual -ne $DllSha256) { throw "SHA-256 $actual does not match the pinned $DllSha256. Nothing was uploaded." }
Write-Host "tdjson.dll: SHA-256 matches the pin ($DllSha256)."

if (-not (Get-Command gh -ErrorAction SilentlyContinue)) { throw 'The gh CLI is required (https://cli.github.com).' }
& gh auth status | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'gh is not logged in: run gh auth login first.' }

$notices = @"
