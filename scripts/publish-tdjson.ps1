official Telegram binary. squeezegram: https://github.com/$Repository

Build
  TDLib version : 1.8.68
  Source        : https://github.com/tdlib/td, commit $SourceCommit
  Target        : Windows x86_64 (needs the Microsoft Visual C++ Redistributable, x64)
  SHA-256       : $($DllSha256.ToLowerInvariant())
  Statically linked: OpenSSL 3.6.5 and zlib 1.3.2 (versions found as strings in the DLL)

